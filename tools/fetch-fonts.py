"""
Vendors the site's webfonts into apps/web/public/fonts/ and writes
apps/web/src/fonts.css.

    python tools/fetch-fonts.py

Why self-host rather than link the CDN:

  1. The Content-Security-Policy in apps/web/public/_headers is `style-src
     'self'` with no font-src override. A CDN stylesheet is blocked outright,
     silently — the page would just render in the fallback stack.
  2. Kionel's whole claim is that a page makes no third-party request. A font
     CDN sees every visitor's IP. Turkish and EU regulators have both treated
     that as a personal-data transfer, and our own privacy notice says we make
     no such call. Loading fonts from Google would make that text false.

Only the latin and latin-ext subsets are kept. latin-ext is the one that
carries Turkish (ğ ş İ ı ç ö ü); dropping it would break the site's own
language.
"""

import pathlib
import re
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "apps" / "web" / "public" / "fonts"
CSS_OUT = ROOT / "apps" / "web" / "src" / "fonts.css"

# A modern UA is required or the API serves TrueType instead of woff2.
UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36")

REQUEST = ("https://fonts.googleapis.com/css2"
           "?family=Source+Serif+4:ital,opsz,wght@0,8..60,400;0,8..60,600;1,8..60,400"
           "&family=IBM+Plex+Sans:wght@400;500;600"
           "&family=IBM+Plex+Mono:wght@400;500"
           "&display=swap")

KEEP_SUBSETS = {"latin", "latin-ext"}


def fetch(url: str) -> bytes:
    return urllib.request.urlopen(
        urllib.request.Request(url, headers={"User-Agent": UA}), timeout=30
    ).read()


def main() -> None:
    css = fetch(REQUEST).decode("utf-8")
    blocks = re.findall(r"/\*\s*([a-z-]+)\s*\*/\s*(@font-face\s*\{[^}]*\})", css)
    if not blocks:
        raise SystemExit("no @font-face blocks returned — the API response changed")

    FONT_DIR.mkdir(parents=True, exist_ok=True)
    faces: list[tuple[str, str, str, str, str]] = []
    written: dict[str, int] = {}

    for subset, block in blocks:
        if subset not in KEEP_SUBSETS:
            continue
        family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        weight = re.search(r"font-weight:\s*(\d+)", block).group(1)
        style = re.search(r"font-style:\s*(\w+)", block).group(1)
        url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
        unicode_range = re.search(r"unicode-range:\s*([^;]+);", block).group(1).strip()

        italic = "-italic" if style == "italic" else ""
        name = f"{family.lower().replace(' ', '-')}-{weight}{italic}-{subset}.woff2"
        if name not in written:
            (FONT_DIR / name).write_bytes(fetch(url))
            written[name] = (FONT_DIR / name).stat().st_size
        faces.append((family, style, weight, name, unicode_range))

    lines = [
        "/**",
        " * Self-hosted webfaces. Generated by tools/fetch-fonts.py — do not edit.",
        " *",
        " * The page makes no third-party request for type: the CSP forbids it and",
        " * the privacy notice promises it. latin-ext is kept because that subset",
        " * carries Turkish.",
        " */",
        "",
    ]
    for family, style, weight, name, unicode_range in faces:
        lines += [
            "@font-face {",
            f"  font-family: '{family}';",
            f"  font-style: {style};",
            f"  font-weight: {weight};",
            "  font-display: swap;",
            f"  src: url('/fonts/{name}') format('woff2');",
            f"  unicode-range: {unicode_range};",
            "}",
        ]
    CSS_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    total = sum(written.values())
    print(f"{len(written)} woff2 · {total / 1024:.0f} KB toplam -> {FONT_DIR}")
    for name in sorted(written):
        print(f"  {name}  {written[name] / 1024:.1f} KB")
    print(f"{len(faces)} @font-face -> {CSS_OUT}")


if __name__ == "__main__":
    main()
